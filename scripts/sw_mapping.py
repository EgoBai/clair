def classify_sw(f100: str) -> str:
    if not f100:
        return '综合'
    k = _norm(f100)
    if k in SW2_TO_SW1:
        return SW2_TO_SW1[k]
    # prefix / contains fallback
    for sw2, sw1 in SW2_TO_SW1.items():
        if k.startswith(sw2) or sw2.startswith(k):
            return sw1
    return '综合'
