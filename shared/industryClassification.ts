/**
 * 股票→子行业分类函数
 * 1. 先从概念标签匹配
 * 2. 再从公司名称关键词匹配
 * 3. 默认使用一级行业下的第一个子行业
 */
export function classifySubIndustry(industry: string, name: string, concepts?: string[]): string {
  const subs = SW_INDUSTRY_MAP[industry];
  if (!subs || subs.length === 0) return industry;

  // 先尝试概念标签匹配
  if (concepts) {
    for (const concept of concepts) {
      for (const sub of subs) {
        const keywords = SUB_INDUSTRY_KEYWORDS[sub];
        if (keywords?.some(kw => concept.includes(kw))) return sub;
      }
    }
  }

  // 再尝试名称匹配
  for (const sub of subs) {
    const keywords = SUB_INDUSTRY_KEYWORDS[sub];
    if (keywords?.some(kw => name.includes(kw))) return sub;
  }

  // 默认第一个
  return subs[0];
}

/**
 * 获取所有二级行业列表（去重后的唯一条目）
 */
export function getAllSubIndustries(): string[] {
  const all: Set<string> = new Set();
  for (const subs of Object.values(SW_INDUSTRY_MAP)) {
    for (const sub of subs) {
      all.add(sub);
    }
  }
  return Array.from(all).sort();
}

/**
 * 获取某个一级行业下的所有子行业
 */
export function getSubIndustries(industry: string): string[] {
  return SW_INDUSTRY_MAP[industry] || [];
}

/**
 * 根据子行业查找所属的一级行业
 */
export function getParentIndustry(subIndustry: string): string | undefined {
  return SUB_TO_PARENT[subIndustry];
}
