/**
 * 指数串位回归测试（P0-IDXBLEED）
 *
 * ## 缺陷
 * `DataSyncService.parseTencentResponse()` 原本只取 `parts[2]`（6 位数字代码），
 * 再用 `getMarketFromSymbol()` 按数字前缀反推交易所。但**指数与个股共用数字代码**：
 *   - `sh000001` = 上证指数，`parts[2]` = '000001'
 *   - `sz000001` = 平安银行，`parts[2]` = '000001'← 同一个数字！
 *   - `sh000905` = 中证500  /  `sz000905` = 厦门港务← 同样是同一个数字
 * 数字 `000001` 以 `0` 开头 → 被判成 SZ，于是**上证指数点位被写进
 * 「000001.SZ 平安银行」那一行**，个股价格曲线被污染。
 *
 * ## 实测危害（本地 PG 实测 + 腾讯线上交叉验证，非推测）
 * `daily_quotes` 里 `000001 平安银行` 曾出现 close=4068.57，
 * 而腾讯 `sh000001`（上证指数）2026-05-29 收盘**恰为** 4068.570；
 * `000905 厦门港务` close=8359.56 = `sh000905`（中证500）同日收盘 8359.560。
 *
 * ## 修法
 * 交易所归属取**响应 key**（`v_sh000001` / `v_sz000001`）的前缀——它由上游明确给出、
 * 不会歧义；仅当 key 无前缀时才退回按数字前缀推断。
 *
 * ## 测试数据
 * `REAL_TENCENT_COLLISION` 是**真实抓取**的腾讯线上报文（已 iconv 转 UTF-8，逐字保留），
 * 不是手编构造——手编极易漏字段（本人第一版就因字段数不足被生产代码的
 * session 时间戳守卫拒绝，正好证明该守卫有效）。
 */

