/**
 * 直接打在**真实生产方法**上（经类型断言取 private 方法），
 * 避免「复制一份逻辑自己测自己」——那种测试在缺陷发生时也会跟着一起错。
 */
function parseQuotes(raw: string) {
  const svc = new DataSyncService();
  const fn = (svc as unknown as {
    parseTencentResponse: (r: string) => Array<{ symbol: string; name: string; currentPrice: number; sessionDate: string }>;
  }).parseTencentResponse;
  return fn.call(svc, raw);
}

describe('P0-IDXBLEED 指数串位回归', () => {
  it('前提：指数与个股的 6 位数字代码确实相同（这正是缺陷根因）', () => {
    const codeOf = (key: string) => {
      const prefix = 'v_' + key + '=';
      const line = REAL_TENCENT_COLLISION.split('\n').find((l) => l.startsWith(prefix))!;
      return line.split('"')[1].split('~')[2];
    };
    expect(codeOf('sh000001')).toBe('000001');
    expect(codeOf('sz000001')).toBe('000001');
    expect(codeOf('sh000905')).toBe('000905');
    expect(codeOf('sz000905')).toBe('000905');
  });

  it('解析出全部 6 条，且名称互不串位', () => {
    const quotes = parseQuotes(REAL_TENCENT_COLLISION);
    expect(quotes).toHaveLength(6);
    const names = quotes.map((q) => q.name).sort();
    expect(names).toEqual(['中证500', '平安银行', '厦门港务', '深证成指', '沪深300', '上证指数'].sort());
  });

  it('交易所取自响应 key：指数不得被认成同名个股', () => {
    const quotes = parseQuotes(REAL_TENCENT_COLLISION);
    const byName = (n: string) => quotes.find((q) => q.name === n)!;

    // 关键断言：个股价格必须是个股价，不能是指数点位
    expect(byName('平安银行').currentPrice).toBeCloseTo(11.78, 2);
    expect(byName('厦门港务').currentPrice).toBeCloseTo(9.23, 2);

    // 指数必须带SH/SZ 前缀，且与个股 symbol 不同
    expect(byName('上证指数').symbol).toBe('000001.SH');
    expect(byName('中证500').symbol).toBe('000905.SH');
    expect(byName('上证指数').symbol).not.toBe(byName('平安银行').symbol);
    expect(byName('中证500').symbol).not.toBe(byName('厦门港务').symbol);
  });

  it('同 symbol 只可能对应同一标的（否则 upsert 会互相覆盖）', () => {
    const quotes = parseQuotes(REAL_TENCENT_COLLISION);
    const seen = new Map<string, string>();
    for (const q of quotes) {
      const prev = seen.get(q.symbol);
      // 同一 symbol 出现两个不同名称 = 串位，会导致后写覆盖先写
      expect(prev, 'symbol ' + q.symbol + ' 同时对应「' + prev + '」与「' + q.name + '」').toBeUndefined();
      seen.set(q.symbol, q.name);
    }
    expect(seen.size).toBe(quotes.length);
  });

  it('sessionDate 仍取自 parts[30]，不受本次改动影响', () => {
    const quotes = parseQuotes(REAL_TENCENT_COLLISION);
    expect(quotes.every((q) => q.sessionDate === '2026-10-08')).toBe(true);
  });
});
