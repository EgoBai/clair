/**
 * 成交额单位换算单一真源
 *
 * ## 为什么必须有这个常量
 * 腾讯行情源的成交额单位是**万元**（实时 qt.gtimg `parts[37]`、K线 newfqkline `idx8`），
 * 而 `daily_quotes.turnover`（numeric(20,2)）的权威口径是**元**。
 *
 * 换算若散落在各采集路径，每新增一个采集点都要"记得乘 10000"——本项目已因此
 * 犯过两次错：`DataSyncService.ts` 实时路径与 `api/stock.ts` 指数解析路径都漏乘，
 * 导致库内出现万元口径残留（P0-TURNOVER-UNIT 迁移 68,191 行才清完）。
 *
 * 故此处为唯一真源：**任何写入 `daily_quotes.turnover` 的路径都必须引用本常量**，
 * 不要再在调用点写字面量 `10000`。
 *
 * ## 取整语义由调用方决定
 * 本常量只管量纲，不管取整：
 * - 实时路径保留小数（上游万元带角分，金额更大，避免二次失真）
 * - K线路径先 `Math.round(wan)` 再乘（与实时路径 parts[37] 逐位对齐）
 */

/** 万元 → 元 换算系数 */
export const WAN_TO_YUAN = 10000;
