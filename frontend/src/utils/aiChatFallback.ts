/**
 * 根据用户问题返回确定性的中文演示回复（离线降级用）。
 * 同一问题 + 同一分类，永远返回同一套文案；若含股票代码，会在文案中保留标的标记。
 */
export function buildFallbackReply(question: string): string {
  const q = question || '';
  const category = detectCategory(q);
  const pool = TEMPLATES[category];
  const rand = lcg(hashStr(q + '|' + category));
  let reply = pool[Math.floor(rand() * pool.length)];

  // 命中个股分类时，把代码原样回显，增强"懂你在问哪只"的体感
  const m = q.match(/\b\d{6}\.(SH|SZ|HK|BJ)\b/i);
  if (m && category === 'stock') {
    reply = reply.replace('该标的', `**${m[0]}**`);
  }
  return reply;
}

export default buildFallbackReply;
